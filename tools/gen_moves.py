#!/usr/bin/env python3
"""Generates moves.h (each species' moves for the firmware) from dex_moves.py, and the chart of
them all for players, docs/MOVES.md.

  python3 tools/gen_moves.py

Combat has no misses, no charge turns and no multi-hit moves, so each move
stores an "effective" power that sums up those gen 1 rules.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from dex_data import DEX
from dex_moves import MOVES, LEARNSETS

# spelling used by the Game Boy games (12 letters at most)
GEN1_NAMES = {
    'Thunder Shock': 'THUNDERSHOCK', 'Thunder Punch': 'THUNDERPUNCH', 'High Jump Kick': 'HI JUMP KICK',
    'Double Slap': 'DOUBLESLAP', 'Vise Grip': 'VICEGRIP', 'Solar Beam': 'SOLARBEAM',
    'Bubble Beam': 'BUBBLEBEAM',
}

# fixed-damage moves (no one-hit KO): they don't fit the formula, but come close to a normal hit
FIXED_DAMAGE = {'Dragon Rage': 60, 'Night Shade': 60, 'Seismic Toss': 60, 'Super Fang': 60, 'Sonic Boom': 40}
# hit 2 to 5 times (or trap for several turns): counted as 3 hits
MULTI_HIT = {'Barrage', 'Comet Punch', 'Double Slap', 'Fury Attack', 'Fury Swipes', 'Pin Missile', 'Spike Cannon',
             'Bind', 'Wrap', 'Clamp', 'Fire Spin'}
DOUBLE_HIT = {'Double Kick', 'Bonemerang', 'Twineedle'}
# spend a turn charging or recovering
TWO_TURNS = {'Solar Beam', 'Razor Wind', 'Skull Bash', 'Sky Attack', 'Dig', 'Fly', 'Hyper Beam'}
# need rules this combat doesn't have: one-hit KO, fainting, putting the rival to sleep...
EXCLUDED = {'Guillotine', 'Horn Drill', 'Fissure', 'Self-Destruct', 'Explosion', 'Dream Eater', 'Counter', 'Bide',
            'Psywave'}


def effective_power(name, power, acc):
    if name in EXCLUDED:
        return 0
    if name in FIXED_DAMAGE:
        return FIXED_DAMAGE[name]
    p = power * (3 if name in MULTI_HIT else 2 if name in DOUBLE_HIT else 1) * acc / 100
    return round(p * 0.6 if name in TWO_TURNS else p)


def full_learnsets():
    """Moves learned before evolving are kept, as in the real game."""
    evo_level = {num: lvl for num, _, _, _, _, lvl in DEX}
    parent = {evo: num for num, _, _, _, evo, _ in DEX if evo}
    for branch in (134, 135, 136):  # Eevee branches in the game code
        parent[branch] = 133

    def learned(num):
        out = {}
        if num in parent:
            for lvl, mid in learned(parent[num]):
                if lvl <= evo_level[parent[num]]:
                    out[mid] = lvl
        for lvl, mid in LEARNSETS[num]:
            if effective_power(MOVES[mid][0], MOVES[mid][2], MOVES[mid][3]) > 0:
                out[mid] = min(lvl, out.get(mid, lvl))
        return sorted((lvl, mid) for mid, lvl in out.items())

    return {num: learned(num) for num, *_ in DEX}


# names as players know them: the dex keeps them in capitals without symbols
SPECIAL_NAMES = {'NIDORAN H': 'Nidoran♀', 'NIDORAN M': 'Nidoran♂', 'FARFETCHD': "Farfetch'd"}


def player_name(display):
    return SPECIAL_NAMES.get(display, display.title())


def write_chart(sets):
    """docs/MOVES.md: every Pokemon, the level it learns each move at, and when it evolves."""
    names = {num: player_name(disp) for num, _, disp, _, _, _ in DEX}
    out = [
        '# Moves\n\n',
        '<!-- GENERATED by tools/gen_moves.py from tools/dex_moves.py - do not edit -->\n\n',
        'Every Pokémon and the level it learns each move at, from its level-up moves in Pokémon Red and Blue. '
        'Only moves that do damage are kept. A Pokémon gains a level every hour of age, up to 100.\n\n',
        '- **Level 1** moves are known from the start.\n',
        '- The number after each move is its **power** as this game counts it: its Red and Blue power with '
        'accuracy, hits in a row and turns spent charging folded in (Struggle is 50). Higher hits harder, so you '
        'can see when an evolved form learns a strong move later than its earlier form does, and when waiting '
        'to evolve is worth it.\n',
        '- **Bold** moves are the Pokémon\'s own type: the strongest of those goes on the right battle button, '
        'and the strongest of the rest on the left. A new move only takes over a button if it is stronger, '
        'so some listed here never show up.\n',
        '- Moves learned before evolving are kept, so an evolved form also lists the ones it could have '
        'learned as its earlier form.\n',
        '- **Evolves** is the level it is ready to evolve at; each care mistake puts that off by a level.\n',
        '- Ditto has no moves of its own: it copies the wild Pokémon\'s. A Pokémon with no move yet fights with Struggle.\n',
        '\nSee [How it works](HOW_IT_WORKS.md#moves) for how moves are picked in a battle.\n\n',
        '| # | Pokémon | Type | Moves by level | Evolves |\n',
        '|---:|---|---|---|---|\n',
    ]
    for num, _, disp, typ, evo, lvl in DEX:
        moves = []
        for lv, mid in sets[num]:
            name, mtype, power, acc = MOVES[mid]
            pw = effective_power(name, power, acc)
            moves.append(f'{lv} **{name}** ({pw})' if mtype == typ else f'{lv} {name} ({pw})')
        if num == 132:
            cell = 'Copies the wild Pokémon\'s moves'
        else:
            cell = ' · '.join(moves) if moves else 'Struggle only'
            if moves and sets[num][0][0] > 1:
                cell = f'Struggle until {sets[num][0][0]} · ' + cell
        if num == 133:
            evolves = 'Vaporeon, Jolteon or Flareon at 30'
        elif evo:
            evolves = f'{names[evo]} at {lvl}'
        else:
            evolves = ''
        out.append(f'| {num} | {names[num]} | {typ.title()} | {cell} | {evolves} |\n')
    path = os.path.join(os.path.dirname(__file__), '..', 'docs', 'MOVES.md')
    with open(path, 'w') as f:
        f.write(''.join(out))
    print('docs/MOVES.md: 151 Pokemon')


def main():
    sets = full_learnsets()
    used = sorted({mid for s in sets.values() for _, mid in s})
    ids = {mid: i + 1 for i, mid in enumerate(used)}  # 0 = STRUGGLE
    out = [
        '#pragma once\n#include <stdint.h>\n#include "dex.h"\n\n',
        '// GENERATED by tools/gen_moves.py from tools/dex_moves.py - do not edit\n\n',
        'struct BtlMove { const char *name; uint8_t type; uint8_t power; };\n',
        'struct LearnEntry { uint8_t level; uint8_t move; };\n\n',
        '// 0: STRUGGLE, what a gen 1 Pokemon with no moves left uses\n',
        'static const BtlMove MOVE_TBL[] = {\n  { "STRUGGLE", TY_NORMAL, 50 },\n',
    ]
    for mid in used:
        name, typ, power, acc = MOVES[mid]
        shown = GEN1_NAMES.get(name, name.upper())
        out.append(f'  {{ "{shown}", TY_{typ.upper()}, {effective_power(name, power, acc)} }},\n')
    out.append('};\n\n// moves per species, in level order: from LEARN_START[dex] up to LEARN_START[dex + 1]\n')
    out.append('static const LearnEntry LEARN_TBL[] = {\n')
    start, n = [0, 0], 0
    for num in range(1, 152):
        out.append('  ' + ''.join(f'{{ {lvl}, {ids[mid]} }}, ' for lvl, mid in sets[num]) + f'// {num}\n')
        n += len(sets[num])
        start.append(n)
    out.append('};\n\nstatic const uint16_t LEARN_START[DEX_COUNT + 2] = {\n  ')
    out.append(', '.join(str(x) for x in start) + '\n};\n')
    path = os.path.join(os.path.dirname(__file__), '..', 'moves.h')
    with open(path, 'w') as f:
        f.write(''.join(out))
    print(f'moves.h: {len(used)} moves, {n} entries')
    write_chart(sets)


if __name__ == '__main__':
    main()
