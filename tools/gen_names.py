#!/usr/bin/env python3
"""Downloads the official per-language names from PokeAPI and writes tools/dex_names.py.

  python3 tools/gen_names.py

Only FR and DE have their own names in gen 1; ES/IT/PT use the English ones, so
only what differs from English is stored here. The GFX font is ASCII, so the
names come out uppercase and without accents.
"""
import json
import os
import subprocess
import time
import unicodedata

LANGS = ('fr', 'de')
LANGS_UTF8 = ('ja-hrkt', 'ko')  # CJK: kept as-is in UTF-8, not as ASCII octal

# Gender convention per language: neither the CP437 table nor any U8g2 unifont
# subset has ♀/♂, so each language chooses what to replace them with.
# The Latin path has always used F/M. Korean uses 암/수
# ("female"/"male"), which read as a word rather than a lone letter, and
# are SEPARATED BY A SPACE: 니드런 암. The space goes inside the replacement
# because only the symbol is being replaced. Both syllables are in
# KS X 1001, and already appear in the table (암나이트, 암스타, 홍수몬). The name is
# four syllables plus a space, against five-syllable entries such as 깨비드릴조, so
# it is not the widest in the table.
GENDER = {'ko': (' 암', ' 수')}
GENDER_DEFAULT = ('F', 'M')


def replace_gender(s, lang=None):
    """Nidoran female/male: ♀ and ♂ do not exist in any font we use.

    Neither the CP437 table in glcdfont.h has them at a printable position, nor
    does any U8g2 unifont subset (japanese*, korean*, chinese*).
    And Arduino_GFX draws nothing when a glyph is missing, it does not even
    advance the cursor, so without this both Nidorans come out with the same name.
    """
    female, male = GENDER.get(lang, GENDER_DEFAULT)
    return s.replace('♀', female).replace('♂', male)


def ascii_up(s):
    """'Salamèche' -> 'SALAMECHE'; keeps the gender symbols as f/m."""
    s = replace_gender(s)
    s = unicodedata.normalize('NFD', s)
    s = ''.join(c for c in s if unicodedata.category(c) != 'Mn')
    return s.upper()


def fetch(num):
    url = f'https://pokeapi.co/api/v2/pokemon-species/{num}/'
    for attempt in range(4):
        r = subprocess.run(['curl', '-s', '--max-time', '25', '-A', 'Mozilla/5.0', url],
                           capture_output=True, text=True)
        if r.returncode == 0 and r.stdout.strip().startswith('{'):
            return json.loads(r.stdout)
        time.sleep(1 + attempt)
    raise SystemExit(f'could not download species {num}')


def main():
    out = {}
    for num in range(1, 152):
        d = fetch(num)
        names = {n['language']['name']: n['name'] for n in d['names']}
        en = ascii_up(names['en'])
        dif = {}
        for lg in LANGS:
            v = ascii_up(names.get(lg, names['en']))
            if v != en:
                dif[lg] = v
        for lg in LANGS_UTF8:
            v = names.get(lg)
            if v:
                # 'ja-hrkt' -> 'ja'; UTF-8 is kept except for ♀/♂, which the
                # font lacks (see replace_gender)
                short = lg.split('-')[0]
                dif[short] = replace_gender(v, short)
        if dif:
            out[num] = dif
        if num % 25 == 0:
            print(f'  {num}/151...')
        time.sleep(0.05)

    path = os.path.join(os.path.dirname(__file__), 'dex_names.py')
    with open(path, 'w', encoding='utf-8') as f:
        f.write('# -*- coding: utf-8 -*-\n')
        f.write('"""GENERATED by tools/gen_names.py from PokeAPI - do not edit by hand.\n\n')
        f.write('Official names per language. FR and DE are uppercase and without\n')
        f.write('accents (CP437 font, one byte per character); JA and KO are\n')
        f.write('plain UTF-8, because they are drawn with a U8g2 font.\n"""\n\n')
        f.write('LOCAL_NAMES = {\n')
        for num in sorted(out):
            f.write(f'    {num}: {out[num]!r},\n')
        f.write('}\n')
    print(f'saved {os.path.normpath(path)}: {len(out)} species with their own name')


if __name__ == '__main__':
    main()
