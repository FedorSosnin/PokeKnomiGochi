#!/usr/bin/env python3
"""The About page's pictures (V2): Fedor's 3D Print SOS logo as pixel art, and its two links as QR codes.

  ~/.venvs/esp/bin/python3 tools/about_assets.py     (needs Pillow, and segno for the QR codes)

- about_logo.h: tools/assets/3dprintsos-logo.png shrunk to 72 x 72, each pixel the average of its area, then the
  nearest of the logo's own colours (no dithering). Around the red ring, drawn at this size so it stays crisp: a dark
  edge, a braided gold rope and a dark edge, and the four black ticks through it. A palette (RGB565, 0 see-through)
  and one index a pixel; the game draws it at 2x and spins it like a coin (about_v2.h).
- about_qr.h: the GitHub repository and the YouTube channel as QR codes (error correction M), a string of 0/1 a row,
  for the Knomi, which can't open a link: the phone scans it.
"""
import math
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
N = 72  # (96 until the game had a logo of its own: Fedor, "the 3DPrintSOS coin a bit smaller and our new logo larger")
LINKS = (('GITHUB', 'https://github.com/FedorSosnin/PokeKnomiGochi'), ('YOUTUBE', 'https://youtube.com/3dprintsos'))
PAL = [
    (0x1E, 0x2A, 0x6D),  # navy: the middle and the letters' outlines
    (0x14, 0x1A, 0x48),  # navy, dark
    (0xA0, 0x1B, 0x26),  # red: the ring
    (0xC2, 0x3E, 0x48),  # red, lit
    (0xFF, 0xFF, 0xFF),  # white: PRINT
    (0xD6, 0xE6, 0xEC),  # pale blue: 3D
    (0xAC, 0xB4, 0xBB),  # grey: the ring's bands
    (0xFD, 0xD8, 0x70),  # yellow: SOS
]
EDGE, ROPE_L, ROPE_D, TICK = (0x14, 0x1A, 0x48), (0xFF, 0xE3, 0xA0), (0xC2, 0xA4, 0x6D), (0x20, 0x20, 0x20)


def logo_pixels():
    from PIL import Image
    im = Image.open(os.path.join(ROOT, 'tools', 'assets', '3dprintsos-logo.png')).convert('RGBA')
    bg = Image.new('RGBA', im.size, (255, 255, 255, 255))
    bg.alpha_composite(im)
    small = bg.convert('RGB').resize((N, N), Image.BOX)
    cx = cy = (N - 1) / 2
    R = N * 0.369  # the red ring's outer edge, as in the source

    def near(p):
        return min(PAL, key=lambda c: (c[0] - p[0]) ** 2 * 2 + (c[1] - p[1]) ** 2 * 4 + (c[2] - p[2]) ** 2 * 3)

    px = [[None] * N for _ in range(N)]
    for y in range(N):
        for x in range(N):
            d = math.hypot(x - cx, y - cy)
            if d <= R:
                c = near(small.getpixel((x, y)))
                if d > R - 2 and c in ((0xFF, 0xFF, 0xFF), (0xD6, 0xE6, 0xEC)):
                    c = (0xA0, 0x1B, 0x26)  # the ring's edge, no white fringe
                px[y][x] = c
            elif d <= R + 1 or R + 4 < d <= R + 5:
                px[y][x] = EDGE
            elif d <= R + 4:  # the rope: slanted strands
                twist = int(math.atan2(y - cy, x - cx) * R / 2.2 + (d - R) * 1.1) % 2
                px[y][x] = ROPE_L if twist else ROPE_D
    mid = (N // 2 - 1, N // 2)
    for k in range(int(R - 1), int(R + 8) + 1):  # the ticks: north, east, south, west, 2 px wide
        for m in mid:
            for x, y in ((m, int(cy - k + 0.5)), (m, int(cy + k + 0.5)), (int(cx - k + 0.5), m), (int(cx + k + 0.5), m)):
                if 0 <= x < N and 0 <= y < N:
                    px[y][x] = TICK
    return px


def write_logo():
    px = logo_pixels()
    pal, idx = [None], []
    for row in px:
        for p in row:
            if p is None:
                idx.append(0)
                continue
            c = ((p[0] >> 3) << 11) | ((p[1] >> 2) << 5) | (p[2] >> 3)
            if c not in pal:
                pal.append(c)
            idx.append(pal.index(c))
    with open(os.path.join(ROOT, 'src', 'about_logo.h'), 'w') as f:
        f.write('// Generated by tools/about_assets.py from tools/assets/3dprintsos-logo.png: do not edit.\n')
        f.write('// The 3D Print SOS logo as pixel art, %d x %d: a palette (RGB565, 0 = see-through), an index a pixel\n' % (N, N))
        f.write('#pragma once\n#include <stdint.h>\n')
        f.write('#define ABOUT_LOGO_N %d\n' % N)
        f.write('static const uint16_t ABOUT_LOGO_PAL[%d] = { 0, %s };\n' % (len(pal), ', '.join('0x%04X' % c for c in pal[1:])))
        f.write('static const uint8_t ABOUT_LOGO[%d] = {\n' % (N * N))
        for y in range(N):
            f.write('  ' + ','.join(str(v) for v in idx[y * N:(y + 1) * N]) + ',\n')
        f.write('};\n')
    print('about_logo.h: %d x %d, %d colours' % (N, N, len(pal) - 1))


def write_qr():
    import segno
    with open(os.path.join(ROOT, 'src', 'about_qr.h'), 'w') as f:
        f.write('// Generated by tools/about_assets.py: do not edit.\n')
        f.write('// The About page\'s links as QR codes (error correction M, no border), a string of 0/1 a row\n#pragma once\n')
        for name, url in LINKS:
            q = segno.make(url, error='m', micro=False)
            rows = [''.join('1' if m else '0' for m in row) for row in q.matrix]
            f.write('#define ABOUT_URL_%s "%s"\n' % (name, url))
            f.write('#define QR_%s_N %d\nstatic const char *const QR_%s[%d] = {\n' % (name, len(rows), name, len(rows)))
            for r in rows:
                f.write('  "%s",\n' % r)
            f.write('};\n')
            print('about_qr.h: %s %d x %d' % (name, len(rows), len(rows)))


if __name__ == '__main__':
    write_logo()
    write_qr()
