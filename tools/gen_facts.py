#!/usr/bin/env python3
"""Generates dexfacts.h from dex_facts.py (text for the Pokedex detail view)."""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from dex_data import TYPE_ACCENTS  # noqa: E402
from dex_facts import FACTS  # noqa: E402

TYPE_NAMES = {
    'normal': 'NORMAL', 'fire': 'FIRE', 'water': 'WATER', 'grass': 'GRASS',
    'electric': 'ELECTRIC', 'ice': 'ICE', 'fighting': 'FIGHTING', 'poison': 'POISON',
    'ground': 'GROUND', 'psychic': 'PSYCHIC', 'bug': 'BUG', 'rock': 'ROCK',
    'ghost': 'GHOST', 'dragon': 'DRAGON',
    'flying': 'FLYING',
}
MAX_LEN = 84


def main():
    for num in range(1, 152):
        text = FACTS[num]
        if len(text) > MAX_LEN or not text.isascii() or '"' in text or '\\' in text:
            sys.exit(f'fact {num} is not valid ({len(text)} characters): {text}')
    out = ['#pragma once\n', '// GENERATED by tools/gen_facts.py from tools/dex_facts.py - do not edit\n\n']
    out.append('static const char *const TYPE_NAME[] = { '
               + ', '.join(f'"{TYPE_NAMES[t]}"' for t in TYPE_ACCENTS) + ' };\n\n')
    out.append('static const char *const DEX_FACT[152] = {\n  "",\n')
    out.extend(f'  "{FACTS[n]}",  // {n}\n' for n in range(1, 152))
    out.append('};\n')
    path = os.path.join(os.path.dirname(__file__), '..', 'dexfacts.h')
    with open(path, 'w', encoding='ascii') as f:
        f.write(''.join(out))
    print('saved dexfacts.h (151 facts)')


if __name__ == '__main__':
    main()
