#!/usr/bin/env python3
"""Generates dex.h (the Pokedex table for the firmware) from dex_data.py.

  python3 tools/gen_dex.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from dex_data import DEX, TYPE_ACCENTS, CLASSIC, RARE, LEGENDARY
from dex_stats import BASE_STATS
from dex_names import LOCAL_NAMES


def rgb565(hexcol):
    r, g, b = int(hexcol[1:3], 16), int(hexcol[3:5], 16), int(hexcol[5:7], 16)
    return (r >> 3) << 11 | (g >> 2) << 5 | (b >> 3)


# background biome per type (the lighting comes from the real RTC time)
# 0 MEADOW, 1 BEACH, 2 FOREST, 3 VOLCANO, 4 MOUNTAIN, 5 SNOW
TYPE_BIOME = {
    'water': 1, 'grass': 2, 'bug': 2, 'fire': 3,
    'rock': 4, 'ground': 4, 'dragon': 1, 'ice': 5,  # gen 1 dragons (Dratini) live in the water
    'normal': 0, 'electric': 0, 'fighting': 0, 'poison': 0,
    'psychic': 0, 'ghost': 0,
}

# exceptions by dex# (the type is not enough): rock/water sea fossils -> beach
BIOME_OVERRIDE = {138: 1, 139: 1, 140: 1, 141: 1}  # Omanyte, Omastar, Kabuto, Kabutops


def main():
    out = []
    out.append("#pragma once\n#include <stdint.h>\n#include \"i18n.h\"  // gLang\n\n")
    out.append("// GENERATED by tools/gen_dex.py from tools/dex_data.py - do not edit\n\n")
    out.append("#define DEX_COUNT 151\n")
    out.append("#define DEX_EEVEE 133  // random branch: 134/135/136\n\n")
    out.append(
        "// rarity: 0 = evolution only, 1 = common, 2 = rare, 3 = legendary\n"
        "enum : uint8_t { R_EVO = 0, R_COMMON, R_RARE, R_LEGENDARY };\n\n"
        "struct DexEntry {\n"
        "  const char *name;\n"
        "  uint8_t evolvesTo;    // dex number, 0 = final form\n"
        "  uint8_t evolveLevel;\n"
        "  uint8_t rarity;       // hatches from an egg if > 0\n"
        "  uint16_t accent;      // RGB565 type color for the UI\n"
        "  uint8_t bHp, bAtk, bDef, bSpe;  // real gen 1 base stats\n"
        "  uint8_t biome;        // 0 meadow 1 beach 2 forest 3 volcano 4 mountain 5 snow\n"
        "  uint8_t type;         // TY_* (a single type per species)\n"
        "};\n\n")
    types = list(TYPE_ACCENTS)
    out.append("enum : uint8_t { " + ", ".join(f"TY_{t.upper()}" for t in types) + ", TY_COUNT };\n\n")
    out.append("static const uint16_t TYPE_ACCENT[TY_COUNT] = { "
               + ", ".join(f"0x{rgb565(TYPE_ACCENTS[t]):04X}" for t in types) + " };\n\n")
    # base forms = those that are nobody's evolution (Eevee's branches are)
    evolved = {evo for *_, evo, _lvl in [(d[4], d[5]) for d in DEX] for evo in [_[0] for _ in [(d[4],) for d in DEX]]}
    evolved = {d[4] for d in DEX if d[4]} | {135, 136}
    rarities = []
    out.append("static const DexEntry DEX_TBL[DEX_COUNT + 1] = {\n")
    out.append('  { "?", 0, 0, 0, 0x2946, 50, 50, 50, 50, 0, TY_NORMAL },  // 0: unused\n')
    for num, slug, display, typ, evo, lvl in DEX:
        acc = rgb565(TYPE_ACCENTS[typ])
        if num in evolved:
            rar = 'R_EVO'
        elif num in LEGENDARY:
            rar = 'R_LEGENDARY'
        elif num in RARE:
            rar = 'R_RARE'
        else:
            rar = 'R_COMMON'
        rarities.append(rar)
        hp, atk, df, spe = BASE_STATS[num]
        bio = BIOME_OVERRIDE.get(num, TYPE_BIOME[typ])
        out.append(f'  {{ "{display}", {evo}, {lvl}, {rar}, 0x{acc:04X}, {hp}, {atk}, {df}, {spe}, {bio}, TY_{typ.upper()} }},  // {num} {typ}\n')
    out.append("};\n\n")

    # Only FR and DE have their own names in gen 1; ES/IT/PT use English.
    out.append(
        "// Official names per language. FR and DE are the only Latin-script ones that differ\n"
        "// from English in gen 1 (ES/IT/PT use the one in DEX_TBL); JA and KO are UTF-8,\n"
        "// drawn with the U8g2 font. nullptr = no name of its own.\n")
    for lg in ('fr', 'de', 'ja', 'ko'):
        out.append(f"static const char *const DEX_NAME_{lg.upper()}[DEX_COUNT + 1] = {{\n")
        row = []
        for num in range(0, 152):
            nm = LOCAL_NAMES.get(num, {}).get(lg)
            row.append(f'"{nm}"' if nm else 'nullptr')
            if len(row) == 4:
                out.append("  " + ", ".join(row) + ",\n")
                row = []
        if row:
            out.append("  " + ", ".join(row) + ",\n")
        out.append("};\n\n")
    out.append(
        "// Species name in the active language (falls back to the DEX_TBL one if that\n"
        "// language has no name of its own for it).\n"
        "static inline const char *dexName(int16_t dex) {\n"
        "  if (dex < 1 || dex > DEX_COUNT) return DEX_TBL[0].name;\n"
        "  const char *n = (gLang == LANG_FR)   ? DEX_NAME_FR[dex]\n"
        "                  : (gLang == LANG_DE) ? DEX_NAME_DE[dex]\n"
        "                  : (gLang == LANG_JA) ? DEX_NAME_JA[dex]\n"
        "                  : (gLang == LANG_KO) ? DEX_NAME_KO[dex]\n"
        "                                       : nullptr;\n"
        "  return n ? n : DEX_TBL[dex].name;\n"
        "}\n\n")

    out.append("// the first egg of a game: classic starters\n")
    out.append("static const int16_t CLASSIC_DEX[] = { %s };\n" % ", ".join(map(str, CLASSIC)))
    out.append(f"#define NUM_CLASSIC_DEX {len(CLASSIC)}\n")
    from collections import Counter
    c = Counter(rarities)
    print(f"bases: {c['R_COMMON']} common, {c['R_RARE']} rare, {c['R_LEGENDARY']} legendary, {c['R_EVO']} evolution-only")

    path = os.path.join(os.path.dirname(__file__), '..', 'dex.h')
    open(path, 'w').write(''.join(out))
    print(f"saved {os.path.normpath(path)} ({len(DEX)} species)")


if __name__ == '__main__':
    main()
